

import re
import unicodedata
from pathlib import Path


# ------------------------------------------------------------
# STEP 1: PROJECT CONFIGURATION
# ------------------------------------------------------------

# Get the directory containing this Python script.
BASE_DIR = Path(__file__).resolve().parent

# Location of extracted PDF output.
OUTPUT_FOLDER = BASE_DIR / "outputs"

# Types of text files to process.
CONTENT_TYPES = [
    "text",
    "image_descriptions",
    "tables"
]


# ------------------------------------------------------------
# STEP 2: GENERAL TEXT NORMALIZATION
# ------------------------------------------------------------

def normalize_text(text):
    """
    Normalize text without removing meaningful information.

    Operations:
    - Normalize Unicode
    - Fix unnecessary whitespace
    - Normalize line endings
    - Remove invisible formatting characters
    - Reduce excessive blank lines

    Preserve:
    - Numbers
    - Units
    - Scientific symbols
    - Meaningful punctuation
    """

    # Normalize Unicode characters.
    text = unicodedata.normalize("NFC", text)

    # Convert Windows line endings to standard newlines.
    text = text.replace("\r\n", "\n")
    text = text.replace("\r", "\n")

    # Replace non-breaking spaces with ordinary spaces.
    text = text.replace("\u00a0", " ")

    # Remove invisible zero-width characters.
    text = text.replace("\u200b", "")
    text = text.replace("\ufeff", "")

    # Replace repeated horizontal whitespace with one space.
    text = re.sub(r"[ \t]+", " ", text)

    # Remove leading and trailing whitespace from each line.
    lines = [
        line.strip()
        for line in text.splitlines()
    ]

    text = "\n".join(lines)

    # Reduce three or more blank lines to one blank line.
    text = re.sub(r"\n{3,}", "\n\n", text)

    return text.strip()


# ------------------------------------------------------------
# STEP 3: REMOVE MARKDOWN FORMATTING
# ------------------------------------------------------------

def remove_markdown_formatting(text):
    """
    Remove unnecessary Markdown formatting.

    Examples:
        **Rover Structure** -> Rover Structure
        ## Rover Structure -> Rover Structure
        *Important* -> Important

    Preserve meaningful scientific symbols and numbers.
    """

    # Remove Markdown heading markers.
    #
    # ## Rover Structure
    # becomes:
    # Rover Structure
    text = re.sub(
        r"(?m)^\s{0,3}#{1,6}\s+",
        "",
        text
    )

    # Remove standalone Markdown dividers.
    #
    # ---
    # ***
    # ___
    text = re.sub(
        r"(?m)^\s*(?:-{3,}|\*{3,}|_{3,})\s*$",
        "",
        text
    )

    # Remove Markdown bold formatting using **.
    #
    # **Six wheels** -> Six wheels
    text = re.sub(
        r"\*\*([^*\n]+)\*\*",
        r"\1",
        text
    )

    # Remove Markdown bold formatting using __.
    #
    # __Navigation Cameras__ -> Navigation Cameras
    text = re.sub(
        r"(?<!\w)__([^_\n]+)__(?!\w)",
        r"\1",
        text
    )

    # Remove Markdown italic formatting using *.
    #
    # *Scientific instruments* -> Scientific instruments
    text = re.sub(
        r"(?<![\w*])\*([^*\n]+)\*(?![\w*])",
        r"\1",
        text
    )

    # Remove Markdown italic formatting using _.
    #
    # _Important_ -> Important
    text = re.sub(
        r"(?<!\w)_([^_\n]+)_(?!\w)",
        r"\1",
        text
    )

    return text


# ------------------------------------------------------------
# STEP 4: CLEAN PDF TEXT
# ------------------------------------------------------------

def clean_pdf_text(text):
    """
    Clean PDF-extracted text conservatively.

    Fix:
    - Whitespace
    - Line endings
    - Some hyphenated line breaks

    Avoid:
    - Removing scientific units
    - Removing numerical values
    - Aggressively joining lines
    """

    # Hyphenated line breaks are already joined in
    # extract_pdf.normalize_paragraph.
    return normalize_text(text)


# ------------------------------------------------------------
# STEP 5: CLEAN VLM IMAGE DESCRIPTIONS
# ------------------------------------------------------------

def clean_image_description(text):
    """
    Clean image descriptions generated by InternVL.

    Remove:
    - Markdown headings
    - Markdown bold and italic markers
    - Unnecessary whitespace
    - Excessive blank lines

    Preserve:
    - Scientific symbols
    - Numbers and measurements
    - Bullet lists
    - Technical descriptions
    """

    # Normalize spacing.
    text = normalize_text(text)

    # Remove Markdown formatting.
    text = remove_markdown_formatting(text)

    # Normalize again after removing formatting.
    return normalize_text(text)


# ------------------------------------------------------------
# STEP 6: CLEAN TABLE TEXT
# ------------------------------------------------------------

def clean_table_text(text):
    """
    Clean extracted tables without damaging their structure.

    Preserve:
    - Row numbers
    - Column labels
    - Numerical values
    - Units
    - Line boundaries
    """

    return normalize_text(text)


# ------------------------------------------------------------
# STEP 7: CLEAN ONE FILE DIRECTLY
# ------------------------------------------------------------

def clean_file(file_path, content_type):
    """
    Read a TXT file, clean its contents,
    and overwrite the SAME file.

    No duplicate file is created.
    """

    # Read original file contents.
    original_text = file_path.read_text(
        encoding="utf-8"
    )

    # Select the appropriate cleaning method.
    if content_type == "text":
        cleaned_text = clean_pdf_text(original_text)

    elif content_type == "image_descriptions":
        cleaned_text = clean_image_description(original_text)

    elif content_type == "tables":
        cleaned_text = clean_table_text(original_text)

    else:
        return False

    # Avoid rewriting files that are already clean.
    if cleaned_text == original_text:
        print(f"Already clean: {file_path.name}")
        return False

    # Overwrite original TXT file.
    file_path.write_text(
        cleaned_text,
        encoding="utf-8"
    )

    print(f"Cleaned: {file_path.name}")

    return True


# ------------------------------------------------------------
# STEP 8: PROCESS ONE PDF DOCUMENT
# ------------------------------------------------------------

def process_document(document_folder):
    """
    Search the text, image_descriptions and tables folders
    and clean their files directly.
    """

    print(
        f"\nProcessing document: {document_folder.name}"
    )

    total_files = 0
    modified_files = 0

    for content_type in CONTENT_TYPES:

        source_folder = document_folder / content_type

        if not source_folder.exists():
            continue

        # Find all TXT files in this folder and subfolders.
        text_files = sorted(
            path
            for path in source_folder.rglob("*")
            if path.is_file()
            and path.suffix.lower() == ".txt"
        )

        print(
            f"\nCategory: {content_type}"
        )

        print(
            f"Found {len(text_files)} text files."
        )

        for file_path in text_files:

            total_files += 1

            try:
                was_modified = clean_file(
                    file_path,
                    content_type
                )

                if was_modified:
                    modified_files += 1

            except (OSError, UnicodeError) as error:

                print(
                    f"Failed to clean {file_path.name}: {error}"
                )

    print(
        f"\nTotal files checked: {total_files}"
    )

    print(
        f"Total files modified: {modified_files}"
    )


# ------------------------------------------------------------
# STEP 9: PROCESS ALL EXTRACTED DOCUMENTS
# ------------------------------------------------------------

def main():

    if not OUTPUT_FOLDER.exists():
        print("Outputs folder does not exist.")
        return

    document_folders = sorted(
        folder
        for folder in OUTPUT_FOLDER.iterdir()
        if folder.is_dir()
    )

    if not document_folders:
        print("No extracted document folders found.")
        return

    print("Starting in-place text cleaning...")

    for document_folder in document_folders:

        process_document(document_folder)

    print("\nText cleaning completed successfully!")


# ------------------------------------------------------------
# PROGRAM ENTRY POINT
# ------------------------------------------------------------

if __name__ == "__main__":
    main()


